import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "AI Software Engineering Platform",
  description:
    "Connect a GitHub repository, understand it with retrieval-augmented search, and let an agent investigate bugs and propose patches.",
};

// Typed explicitly rather than via Next's generated `LayoutProps` global, so
// that `tsc --noEmit` works standalone in CI without a prior `next build`.
export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
